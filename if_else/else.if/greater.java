public class greater {

    public static void main(String[] args) {

        int x = 5;
        int y = 10;

        if (x == y) {
            System.out.println("equal");
        }
        else if (x > y) {
            System.out.println("greater");
        }
        else {
            System.out.println("smaller");
        }

    }
}
