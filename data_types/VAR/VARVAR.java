public class VARVAR {
    public static void main(String[] args) {
        var myNum = 5; // int
        var myDouble = 9.98; // double
        var myChar = 'D'; // char
        var myBoolean = true; // boolean
        var myString = "Hello"; // String
        System.err.println(myNum);
        System.err.println(myDouble);
        System.err.println(myChar);
        System.err.println(myBoolean);
        System.err.println(myString);
    }
}